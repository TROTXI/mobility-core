// What a client does next for every error code the API can return.
//
// Every response's error.code is listed here with the action a client takes
// and one line of guidance. build-contract.mjs attaches the codes to the shared
// ErrorNNN responses as x-error-codes, and services/api-next/tests/
// error-codes.test.ts fails when the API raises a code that is not listed, or
// lists one it no longer raises. Adding a refusal therefore means deciding
// here what the apps should do about it.

